const dictionaries: Record<AppLanguage, MessageTree> = {
  fr,
  en,
};

function resolvePath(source: MessageTree, path: string): string {
  return path.split('.').reduce<unknown>((current, segment) => {
    if (!current || typeof current !== 'object') return undefined;
    return (current as MessageTree)[segment];
  }, source) as string;
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_match, key: string) => {
    const value = params[key];
    return value === undefined || value === null ? '' : String(value);
  });
}

export function translate(language: AppLanguage, key: string, params?: Record<string, string | number>): string {
  const template = resolvePath(dictionaries[language], key) || resolvePath(dictionaries.fr, key) || key;
  return interpolate(template, params);
}
